#pragma once

#include <Arduino.h>
#include <XPT2046_Touchscreen.h>
#include <SPI.h>

class TouchDriver
{
public:

    // ============================================
    // TOUCH OBJECT
    // ============================================

    XPT2046_Touchscreen* ts;

    // ============================================
    // TOUCH STATE
    // ============================================

    uint16_t touchX;
    uint16_t touchY;

    bool touched;

    // ============================================
    // CONSTRUCTOR
    // ============================================

    TouchDriver();

    // ============================================
    // INIT
    // ============================================

    void begin();

    // ============================================
    // UPDATE TOUCH
    // ============================================

    bool update();

    // ============================================
    // GETTERS
    // ============================================

    uint16_t getX();

    uint16_t getY();

    bool isTouched();

private:

    // ============================================
    // RAW TOUCH
    // ============================================

    uint16_t rawX;

    uint16_t rawY;

    // ============================================
    // CALIBRATION
    // ============================================

    static const uint16_t X_MIN = 100;
    static const uint16_t X_MAX = 4000;

    static const uint16_t Y_MIN = 100;
    static const uint16_t Y_MAX = 4000;
};

// ============================================
// GLOBAL INSTANCE
// ============================================

extern TouchDriver Touch;